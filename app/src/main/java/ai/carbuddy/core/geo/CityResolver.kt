    private data class C(val province: String, val name: String, val lat: Double, val lng: Double)

    override fun resolve(lat: Double, lng: Double): City? {
        val best = CITIES.minByOrNull { Geo.distanceM(lat, lng, it.lat, it.lng) } ?: return null
        if (Geo.distanceM(lat, lng, best.lat, best.lng) > maxDistanceM) return null
        val full = if (best.name == best.province) best.name else "${best.province} ${best.name}"
        val short = when {
            best.province == "서울" -> "서울"
            best.name.length > 2 && best.name.last() in "시군구" -> best.name.dropLast(1)
            else -> best.name
        }
        return City(full, short)
    }

