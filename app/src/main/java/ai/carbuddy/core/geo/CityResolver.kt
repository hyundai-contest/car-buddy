/** A 시·군·구 level place name. Cards only ever carry this level (SPEC 1장 원칙 5). */
data class City(val full: String, val short: String)

fun interface CityResolver { fun resolve(lat: Double, lng: Double): City? }

/**
 * Offline nearest-centroid lookup over a built-in list (Seoul 구, major 시·군).
 * TODO: replace with a reverse-geocoding API + cache (기획안 부록: 외부 API, 실패 시 시·군 생략).
